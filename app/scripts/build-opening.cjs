// Bundles opening/opening.js (three.js + GSAP) into one offline HTML string at src/openingHtml.ts.
// Run after editing the scene: NODE_PATH=<dir with esbuild> node scripts/build-opening.cjs
const path = require('path'), fs = require('fs');
const esbuild = require(require.resolve('esbuild', { paths: [process.cwd(), process.env.NODE_PATH || '', '/Users/kabir/jobless-board/node_modules'] }));
const root = path.join(__dirname, '..');
const out = esbuild.buildSync({ entryPoints: [path.join(root, 'opening/opening.js')], bundle: true, minify: true, format: 'iife', target: 'safari15', write: false });
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = fs.readFileSync(path.join(root, 'opening/template.html'), 'utf8').replace('/*BUNDLE*/', () => js);
fs.writeFileSync(path.join(root, 'src/openingHtml.ts'), '// Generated by scripts/build-opening.cjs. Do not edit.\nexport const OPENING_HTML = ' + JSON.stringify(html) + ';\n');
console.log('openingHtml.ts', (html.length / 1024).toFixed(0) + ' KB');
